import assert from 'node:assert/strict';
import { fetchHomeProducts } from '../src/utils/homeProductLoader.mjs';
const response = products => ({data:{success:true,data:{products}}});
const one = [{_id:'p1',name:'Cocoon'}];
let seen = [];
let result = await fetchHomeProducts(async (url,options)=>{seen.push(options.params);return response(one);});
assert.equal(result.source,'featured');assert.equal(seen.length,1);
seen=[];
result = await fetchHomeProducts(async (url,options)=>{seen.push(options.params);return response(options.params.featured ? [] : one);});
assert.equal(result.source,'sellable'); assert.equal(seen.length,2);
seen=[];
result=await fetchHomeProducts(async (url,options)=>{seen.push(options.params);if(options.params.featured)throw Error('503');return response(one);});
assert.equal(result.source,'sellable');assert.equal(seen.length,2);
seen=[];
result=await fetchHomeProducts(async (url,options)=>{seen.push(options.params);return response(options.params.sellableOnly?[]:one);});
assert.equal(result.source,'catalog'); assert.equal(seen.length,3);
result=await fetchHomeProducts(async()=>response([]));assert.equal(result.source,'empty');
await assert.rejects(fetchHomeProducts(async()=>{throw Error('network');}),/network/);
await assert.rejects(fetchHomeProducts(async()=>({data:{}})),/không hợp lệ/);
console.log('SANDWICH_HOME_FEATURED_FALLBACK_PASS: featured, sellable, catalog, network, empty, invalid-response');
