const assert = require('node:assert/strict');
const catalog = require('../data/catalog48Drafts.json');
const { validate, draftDocument } = require('./importCatalog48Drafts');
const report = validate(catalog);
assert.equal(report.total, 48);
assert.equal(report.newCandidates, 47);
const sample = catalog.find(x => !x.isExistingProduct);
const doc = draftDocument(sample, { _id:'brand-local-fixture'}, { _id:'category-local-fixture'});
assert.equal(doc.isActive, false);
assert.equal(doc.basePrice, 0);
assert.equal(doc.images.length, 0);
assert.equal(doc.keyIngredients.length, sample.keyIngredients.length);
assert.equal(doc.brand, sample.brand);
assert.equal(doc.salePrice, null);
assert(!('stock' in doc));
assert(!('sku' in doc));
const old = JSON.parse(JSON.stringify(catalog)); old[0].slug=old[1].slug;
assert.throws(()=>validate(old),/DUPLICATE_SLUG/);
console.log('CATALOG_48_OFFLINE_TESTS: PASS | 48 names | 10 brands | 47 draft candidates | zero inventory | no image claims');
