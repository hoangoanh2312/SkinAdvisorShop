const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { validateManifest, signature } = require('./syncCatalogImages48');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'data', 'catalog48ImageMap.json'), 'utf8'));
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'data', 'catalog48Drafts.json'), 'utf8'));
const result = validateManifest({ manifest, catalog });
assert.equal(result.total, 48);
assert.equal(result.mapped, 46);
assert.equal(result.missing.length, 2);
assert.deepEqual(result.missing.map(e => e.number), [1, 40]);
assert.equal(result.entries.length, 46);
assert.equal(new Set(result.entries.map(e => e.slug)).size, 46);
assert.equal(new Set(result.entries.map(e => e.file)).size, 46);
assert.equal(signature(Buffer.from('89504e470d0a1a0a', 'hex')), 'image/png');
assert.equal(signature(Buffer.from('ffd8ffe000', 'hex')), 'image/jpeg');
assert.equal(signature(Buffer.concat([Buffer.from('RIFF'), Buffer.alloc(4), Buffer.from('WEBP')])), 'image/webp');
assert.equal(signature(Buffer.from('<html>Access Denied</html>')), null);
const corrupted = structuredClone(manifest);
corrupted[9].file = '../backend/.env';
assert.throws(() => validateManifest({ manifest: corrupted, catalog }), /INVALID_ASSET_MAPPING/);
const swapped = structuredClone(manifest);
swapped[3].slug = swapped[2].slug;
assert.throws(() => validateManifest({ manifest: swapped, catalog }), /MISMATCH_OR_DUPLICATE_ROW/);
console.log(`SKINORA offline image mapping test: PASS (${result.mapped}/48 local files, 2 intentionally missing; no database writes)`);
