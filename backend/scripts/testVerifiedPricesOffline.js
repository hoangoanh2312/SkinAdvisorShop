'use strict';
const assert=require('node:assert/strict');
const quotes=require('../data/catalog48VerifiedRetailQuotes20261023.json');
const {validate,isDraftEligible,previewChanges}=require('./syncCatalogVerifiedRetailPrices');
assert.deepEqual([validate().newSourceQuotes,validate().priorPricesPreserved,validate().needsRecheck],[35,7,6]);
const verified=quotes.filter(q=>q.status==='VERIFIED_SOURCE_QUOTE');
const p={_id:'product1',slug:verified[0].slug,basePrice:0,salePrice:null,isActive:false};
const v={_id:'variant1',product:'product1',sku:verified[0].sku,size:verified[0].size.replace(/(ml|g)$/,''),unit:verified[0].size.match(/(ml|g)$/)[0],price:0,salePrice:null,stock:0,isActive:false};
assert.equal(isDraftEligible(p,[v],verified[0]),null);
assert.equal(previewChanges([verified[0]],[p],[v]).planned.length,1);
assert.equal(isDraftEligible({...p,isActive:true},[v],verified[0]),'PRODUCT_ACTIVE_PRESERVED');
assert.equal(isDraftEligible({...p,basePrice:120000},[v],verified[0]),'PRODUCT_PRICE_ALREADY_SET_PRESERVED');
assert.equal(isDraftEligible(p,[{...v,stock:1}],verified[0]),'STOCK_OR_STATUS_NOT_DRAFT');
assert.equal(isDraftEligible(p,[{...v,price:10000}],verified[0]),'VARIANT_PRICE_ALREADY_SET_PRESERVED');
assert.equal(isDraftEligible(p,[{...v,isActive:true}],verified[0]),'STOCK_OR_STATUS_NOT_DRAFT');
assert.equal(isDraftEligible(p,[{...v,sku:'SOME-OTHER-SKU'}],verified[0]),'SKU_NOT_MATCHED');
assert.equal(isDraftEligible(p,[{...v,size:'12'}],verified[0]),'SIZE_NOT_MATCHED');
assert.equal(isDraftEligible(p,[v,v],verified[0]),'EXPECTED_EXACTLY_ONE_VARIANT');
assert.equal(previewChanges([verified[0]],[{...p,basePrice:verified[0].priceVND}],[{...v,price:verified[0].priceVND}]).planned.length,0);
assert.equal(previewChanges(quotes,[],[]).planned.length,0);
console.log('SKINORA_PRICE_GUARD_OFFLINE_PASS: 35 quotes, 7 old preserved, 6 pending; only exact inactive stock-0 zero-price SKUs can be updated; repeated apply will skip');
